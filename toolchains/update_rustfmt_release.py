#!/usr/bin/env python3
"""Writes rustfmt_release.bzl, the nightly rustfmt archives Buck2 downloads.

Records the URL and SHA-256 of the rustfmt and rustc archives (rustfmt
links against the rustc libraries) of the nightly that RUSTFMT_NIGHTLY
names, for each supported host, from the release manifest on
https://static.rust-lang.org/dist. .rustfmt.toml uses options that only a
nightly rustfmt accepts. The Rust release itself is pinned by the xbox360
cell (rust-toolchain.toml names the same release).

Run it after changing RUSTFMT_NIGHTLY. With --check, only verifies that
rustfmt_release.bzl was generated for it.
"""

import argparse
import ast
import sys
import tomllib
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUTPUT = HERE / "rustfmt_release.bzl"
DIST_URL = "https://static.rust-lang.org/dist"

RUSTFMT_NIGHTLY = "2026-10-14"

COMPONENTS = ["rustc", "rustfmt-preview"]

# Buck2 `prelude//os` and `prelude//cpu` constraint names to Rust host
# triples. These are the hosts that reindeer.toml defines platforms for;
# build_defs/update_buck_files.py resolves dependencies for the same.
HOSTS = {
    "linux": {
        "x86_64": "x86_64-unknown-linux-gnu",
    },
    "macos": {
        "arm64": "aarch64-apple-darwin",
    },
    "windows": {
        "x86_64": "x86_64-pc-windows-msvc",
    },
}


def archive(manifest, component, triple):
    entry = manifest["pkg"][component]["target"][triple]
    if not entry.get("available", False):
        raise SystemExit(f"error: {component} is not available for {triple}")
    return entry["xz_url"], entry["xz_hash"]


def render(manifest):
    lines = [
        '"""Nightly rustfmt archives that Buck2 downloads.',
        "",
        f"Generated by update_rustfmt_release.py for the {RUSTFMT_NIGHTLY} nightly; do not edit.",
        '"""',
        "",
        f'RUSTFMT_NIGHTLY = "{RUSTFMT_NIGHTLY}"',
        "",
        "# os -> cpu -> host triple and component archives, in the layout of",
        "# RUST_HOSTS in @xbox360//buck:rust_release.bzl.",
        "RUSTFMT_HOSTS = {",
    ]
    for os_name, cpus in HOSTS.items():
        lines.append(f'    "{os_name}": {{')
        for cpu, triple in cpus.items():
            lines.append(f'        "{cpu}": {{')
            lines.append(f'            "triple": "{triple}",')
            lines.append('            "archives": {')
            for component in COMPONENTS:
                url, sha256 = archive(manifest, component, triple)
                lines.append(f'                "{component}": {{')
                lines.append(f'                    "sha256": "{sha256}",')
                lines.append(f'                    "url": "{url}",')
                lines.append("                },")
            lines.append("            },")
            lines.append("        },")
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def generated_nightly():
    for node in ast.parse(OUTPUT.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and [t.id for t in node.targets if isinstance(t, ast.Name)] == ["RUSTFMT_NIGHTLY"]:
            return ast.literal_eval(node.value)
    raise SystemExit(f"error: {OUTPUT} does not assign RUSTFMT_NIGHTLY")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify rustfmt_release.bzl without downloading")
    args = parser.parse_args()

    if args.check:
        if generated_nightly() != RUSTFMT_NIGHTLY:
            print(f"error: {OUTPUT.name} is stale; run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0

    url = f"{DIST_URL}/{RUSTFMT_NIGHTLY}/channel-rust-nightly.toml"
    with urllib.request.urlopen(url, timeout=60) as response:
        manifest = tomllib.load(response)
    OUTPUT.write_text(render(manifest), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
